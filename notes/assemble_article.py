"""Assemble article-complet-v2.md from the reviewed parts, without changing their content.

Run: python3 -I notes/assemble_article.py
Takes the bodies of Introduction et Discussion v3, Méthodes v5 and Résultats v3 (the version-history paragraphs at the top
of each note are left out), demotes their headings by one level, and adds the title, the abstract, the references and the
tables generated by figures/make_figures.py. The figures are linked as PNG files next to the tables.
"""
from pathlib import Path

N = Path(__file__).resolve().parent
PARTS = {"intro": "article-intro-discussion-v3.md", "methodes": "article-methodes-v6.md", "resultats": "article-resultats-v3.md",
         "references": "article-references-v2.md"}
TITLE = ("Recettes exploratoires sur encodeur gelé pour l'Iconclass : un accord de catalogue sur ICAI, aucune brique retenue "
         "sur un banc du Rijksmuseum gelé, et des diagnostics")
ABSTRACT = (
    "Sur des traits gelés de C-RADIOv3-L, une recette de tête améliore-t-elle l'accord des notations Iconclass prédites avec le "
    "catalogue, à la fois sur ICAI et sur un banc du Rijksmuseum ? La série est exploratoire ; relectures et jugements sont faits "
    "par des modèles, sans regard humain. En phase 1, sept comparaisons et une règle conjointe sont écrites avant la mesure, et "
    "les prédictions gelées avant les scores. Aucune brique n'est retenue : deux recettes améliorent l'accord ICAI, mais leurs "
    "intervalles au Rijksmuseum contiennent zéro. En phase 2, une décision maximisant le F1 sous une loi tirée des voisins bat "
    "la référence B (T-Z) sur la validation ICAI, surtout grâce à cette loi. Un seuil sur une loi de voisins réglée séparément "
    "(η = 1), figé et mesuré une fois sur le dev du Rijksmuseum, n'établit pas de transfert, sur un banc filtré aux seuils "
    "préinscrits, qui retire les images très proches de l'apprentissage au sens de ces seuils. Deux sondes (traîne, profondeur) "
    "et des champs de preuve hiérarchiques sont négatifs ; un prototype de distillation de graphes de scène donne « pas de "
    "signal » selon sa règle préinscrite, sans réfuter la distillation. Des diagnostics descriptifs ne tranchent pas la cause "
    "de l'écart entre banques. Le F1 mesure un accord avec un catalogue, pas une justesse visuelle.")
TABLES = ["tableau1_effectifs.md", "tableau2_phase1.md", "tableau3_diagnostic_validation.md", "tableau4_audit.md",
          "tableau5_non_transfert.md", "tableau6_a1.md", "tableau7_d3.md", "tableau8_p9a.md", "tableau9_petit_eleve.md"]
FIGURES = [("figure1_phase1_ecarts.png", "Figure 1 — Phase 1 : écarts et IC95 sur ICAI et sur le Rijksmuseum ; aucune brique retenue."),
           ("figure2_non_transfert.png", "Figure 2 — Non-transfert, descriptif ; sans cause établie."),
           ("figure3_a1_dev.png", "Figure 3 — A1-dev : transfert non établi."),
           ("figure4_p9a.png", "Figure 4 — P9-A, graine 0 : aucun bras retenu."),
           ("figure5_petit_eleve.png", "Figure 5 — Petit élève : les bras 28×28 ne battent pas l'a priori ; bras 8×8 en panneau descriptif.")]


def demote(text):
    return "\n".join("#" + l if l.startswith("#") else l for l in text.split("\n"))


def from_marker(text, marker, until=None):
    i = text.index(marker)
    j = text.index(until, i) if until else len(text)
    return text[i:j].strip()


def main():
    t = {k: (N / v).read_text() for k, v in PARTS.items()}
    intro = from_marker(t["intro"], "## Introduction", "## Discussion")
    discussion = from_marker(t["intro"], "## Discussion")
    methodes = from_marker(t["methodes"], "Ce texte décrit des **méthodes**.")
    resultats = from_marker(t["resultats"], "Ce texte est écrit **uniquement**")
    words = len(ABSTRACT.split())
    out = [f"# {TITLE}", "",
           "Article complet v2, privé, 30 octobre 2026. Assemblé par `notes/assemble_article.py` à partir de "
           + ", ".join(f"`{v}`" for v in PARTS.values()) + " et des tableaux de `notes/figures/`, sans changement de fond.", "",
           f"## Résumé ({words} mots)", "", ABSTRACT, "",
           "## 1. Introduction", "", demote(intro.replace("## Introduction", "", 1).strip()), "",
           "## 2. Méthodes", "", demote(methodes), "",
           "## 3. Résultats", "", demote(resultats), "",
           "## 4. Discussion", "", demote(discussion.replace("## Discussion", "", 1).strip()), "",
           demote(t["references"]).replace("### Références", "## Références", 1), "",
           "## Tableaux", ""]
    for name in TABLES:
        out += [demote((N / "figures" / name).read_text().strip()), ""]
    out += ["## Figures", "", "Les PNG sont produits par `notes/figures/make_figures.py` (non versionnés : `.gitignore`).", ""]
    for name, caption in FIGURES:
        out += [f"![{caption}](figures/{name})", "", f"*{caption}*", ""]
    (N / "article-complet-v2.md").write_text("\n".join(out))
    print("article-complet-v2.md written; abstract words:", words)


if __name__ == "__main__":
    main()
